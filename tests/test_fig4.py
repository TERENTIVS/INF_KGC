"""
test_fig4.py — Reproduction test for manuscript Figure 4.

Verifies that data/fig4_top20_targets.csv (generated by generate_fig4_data.py)
matches the values cited in the paper:
  - 20 rows (top 20 targets)
  - Top target is CXCL8 (Gene::3576) with 333 AEs
  - Top-20 AE sum == 2,997
  - Top-20 share of 6,657 total associations ≈ 45%
"""

import pandas as pd
import pytest
from pathlib import Path

DATA_FILE = Path(__file__).resolve().parent.parent / "data" / "fig4_top20_targets.csv"
TOTAL_GT_ASSOCIATIONS = 6657


@pytest.fixture(scope="module")
def top_targets():
    if not DATA_FILE.exists():
        pytest.skip(
            f"{DATA_FILE} not found. Run generate_fig4_data.py with the "
            "Neo4j database running to create it."
        )
    return pd.read_csv(DATA_FILE)


def test_row_count(top_targets):
    """Figure 4 shows exactly the top 20 targets."""
    assert len(top_targets) == 20


def test_top_gene_identity(top_targets):
    """CXCL8 (Gene::3576) should be the most-connected target — cited in the paper."""
    top_row = top_targets.iloc[0]
    assert top_row["Gene"] == "Gene::3576", (
        f"Expected Gene::3576 (CXCL8) at rank 1, got {top_row['Gene']}"
    )
    assert top_row["Gene_name"] == "CXCL8", (
        f"Expected common name CXCL8, got {top_row['Gene_name']}"
    )


def test_top_gene_ae_count(top_targets):
    """CXCL8 has 333 AEs — mentioned explicitly in the paper."""
    assert int(top_targets.iloc[0]["AEs"]) == 333


def test_top20_sum(top_targets):
    """Top-20 targets account for 2,997 associations — stated exactly in the paper."""
    assert int(top_targets["AEs"].sum()) == 2997


def test_top20_share(top_targets):
    """Top-20 targets account for ~45% of total associations — stated in the paper."""
    share = top_targets["AEs"].sum() / TOTAL_GT_ASSOCIATIONS
    assert 0.44 <= share <= 0.46, (
        f"Expected ~45% share, got {share:.1%}"
    )


def test_ae_counts_descending(top_targets):
    """Rows should be ranked highest-to-lowest AE count."""
    counts = top_targets["AEs"].tolist()
    assert counts == sorted(counts, reverse=True)
